let language;
try { language = localStorage.getItem('sharecost-language'); } catch { /* Storage may be disabled. */ }
if (!['zh', 'en'].includes(language)) language = navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';

function t(key) {
  if (language === 'zh') return key;
  if (Object.hasOwn(english, key)) return english[key];
  const validation = /^(.*)不能为空，且最多 (\d+) 个字符$/.exec(key);
  if (validation) return `${t(validation[1])} is required and must be at most ${validation[2]} characters.`;
  return key;
}

function applyLanguage() {
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = `ShareCost · ${t('一起记，轻松分')}`;
  document.querySelector('meta[name="description"]').content = language === 'zh'
    ? 'ShareCost 共享记账，让每一笔生活开销都有迹可循。多人账本、收支统计与 AA 分摊。'
    : 'Track expenses together, split fairly, and settle up. Shared ledgers, budgets, and spending insights.';
  document.querySelector('#modal').setAttribute('aria-label', t('操作窗口'));
  const loading = document.querySelector('.loading');
  if (loading) loading.textContent = t('正在翻开你的账本…');
}

applyLanguage();
